import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
const fixture=Buffer.from(execFileSync('uv',['run','--project','../backend','--directory','../backend','python','-m','tests.export_synthetic'],{encoding:'utf8'}).trim(),'base64');

test('select grouped receipts and download a single PDF or complete ZIP',async({page},testInfo)=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');await mkdir('../tmp/visual',{recursive:true});
  await page.screenshot({path:`../tmp/visual/${testInfo.project.name}-initial.png`,fullPage:true});
  await page.locator('#file').setInputFiles({name:'synthetic.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:fixture});
  await page.getByRole('button',{name:'Analizar archivo'}).click();
  await expect(page.getByRole('heading',{name:'Seleccionar boletas'})).toBeVisible();
  await expect(page.getByText('3 de 3 seleccionadas')).toBeVisible();
  await expect(page.getByRole('button',{name:'Descargar PDFs en ZIP'})).toBeDisabled();
  await expect(page.getByRole('button',{name:'Descargar Excel',exact:true})).toBeDisabled();
  await expect(page.getByRole('button',{name:'Descargar todo (ZIP)',exact:true})).toBeDisabled();
  await expect(page.getByRole('button',{name:'Editar',exact:true})).toHaveCount(0);
  await expect(page.getByRole('region',{name:'Área Administración'})).toBeVisible();
  await expect(page.getByRole('region',{name:'Área Operaciones'})).toBeVisible();
  const all=page.getByRole('checkbox',{name:'Seleccionar todas las boletas',exact:true});
  await expect(all).toBeChecked();
  await page.getByRole('checkbox',{name:'Seleccionar área Administración',exact:true}).uncheck();
  await expect(page.getByText('1 de 3 seleccionadas')).toBeVisible();
  await expect(all).toHaveJSProperty('indeterminate',true);
  await all.check();await all.uncheck();
  await expect(page.getByText('0 de 3 seleccionadas')).toBeVisible();
  await expect(page.getByRole('button',{name:'Revisar boletas'})).toBeDisabled();
  await page.getByRole('checkbox',{name:'Seleccionar Segunda persona (S-002)',exact:true}).check();
  await expect(page.getByText('1 de 3 seleccionadas')).toBeVisible();
  await expect(page.getByRole('group',{name:'Período de honorarios',exact:true})).toHaveCount(0);
  const payroll=page.getByRole('group',{name:'Período de pago',exact:true});
  await expect(page.getByText(/Observaciones \(/)).toHaveCount(0);
  await expect(page.locator('input[type="date"]')).toHaveCount(0);
  await payroll.getByRole('button',{name:'Desde',exact:true}).click();
  const calendar=page.locator('[data-slot="popover-content"]');
  await expect(calendar).toBeVisible();
  await page.screenshot({path:`../tmp/visual/${testInfo.project.name}-calendar.png`,fullPage:true});
  await page.keyboard.press('Escape');
  await expect(payroll.getByRole('button',{name:'Desde',exact:true})).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(calendar).toBeVisible();
  await calendar.locator('button[data-day="3/16/2026"]').click();
  await expect(calendar).toHaveCount(0);
  await payroll.getByRole('button',{name:'Hasta',exact:true}).click();
  await calendar.locator('button[data-day="3/31/2026"]').click();
  await expect(payroll.getByRole('checkbox')).toHaveCount(0);
  await page.getByRole('button',{name:'Revisar boletas'}).click();
  await expect(page.getByText('Revisión validada. Puedes descargar las boletas.')).toBeVisible();
  await page.getByRole('region',{name:'Área Operaciones'}).getByRole('button',{name:'Ver PDF',exact:true}).click();
  await expect(page.getByTitle('Vista previa de la boleta')).toBeVisible();
  const pdfPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Descargar boleta PDF',exact:true}).click();
  const pdf=await pdfPromise;expect(pdf.suggestedFilename()).toMatch(/^boletas_planilla_.*\.pdf$/);await pdf.delete();
  await page.getByRole('checkbox',{name:'Seleccionar área Administración',exact:true}).check();
  await expect(page.getByRole('button',{name:'Descargar PDFs en ZIP'})).toBeDisabled();
  await expect(page.getByTitle('Vista previa de la boleta')).toHaveCount(0);
  await expect(page.getByRole('group',{name:'Período de pago',exact:true})).toHaveCount(1);
  await expect(payroll.getByRole('checkbox')).toHaveCount(0);
  await page.getByRole('button',{name:'Revisar boletas'}).click();
  await expect(page.getByText('Revisión validada. Puedes descargar las boletas.')).toBeVisible();
  await expect(page.getByLabel('Buscar personas o áreas')).toHaveCount(0);
  await expect(page.getByText('3 de 3 seleccionadas')).toBeVisible();
  const zipPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Descargar PDFs en ZIP'}).click();
  const zip=await zipPromise;expect(zip.suggestedFilename()).toBe('boletas_procontel.zip');await zip.delete();
  const excelPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Descargar Excel',exact:true}).click();
  const excel=await excelPromise;expect(excel.suggestedFilename()).toBe('boletas_procontel.xlsx');await excel.delete();
  const bothPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Descargar todo (ZIP)',exact:true}).click();
  const both=await bothPromise;expect(both.suggestedFilename()).toBe('boletas_procontel.zip');await both.delete();
  await page.screenshot({path:`../tmp/visual/${testInfo.project.name}-review.png`,fullPage:true});
  expect(await page.evaluate(()=>({local:localStorage.length,session:sessionStorage.length}))).toEqual({local:0,session:0});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  await page.getByRole('button',{name:'Limpiar',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Seleccionar boletas'})).toHaveCount(0);
  expect(errors).toEqual([]);
});

